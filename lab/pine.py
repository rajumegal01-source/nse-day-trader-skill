TITLES = dict(orb="Opening Range Breakout", fvg="Fair Value Gap retest", structure="Market structure BOS / CHoCH",
              pdhl="Previous-day high / low", cpr="Central Pivot Range", swing_breakout="Swing breakout (daily)")
INTRADAY = ("orb", "fvg", "structure", "pdhl", "cpr")


def memory_params(symbol, path=MEMORY):
    """{setup: params} from memory.json's best setting of each lab setup for `symbol` ({} if none)."""
    if not symbol or not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        info = json.load(fh).get("stocks", {}).get(symbol.upper())
    out = {}
    for name in ("fvg", "structure", "pdhl", "cpr"):
        best = ((info or {}).get("setups", {}).get(name) or {}).get("best") or []
        if best:
            out[name] = best[0]["p"]
    return out


def params(name, mem):
    p = dict(DEFAULTS[name])
    for k, v in (mem.get(name) or {}).items():
        if k in p:
            p[k] = v
    if "tgt" in p:
        p["tgt"] = 0.0 if p["tgt"] == "eod" else float(p["tgt"])
    if "dead" in p:
        p["dead_hhmm"] = "%d%02d" % divmod(int(p["dead"]), 60)
    if "minpct" in p:
        p["minpct_pct"] = round(p["minpct"] * 100, 4)
    if "buf" in p:
        p["buf_pct"] = round(p["buf"] * 100, 4)
    return p


def fill(text, values):
    for k, v in values.items():
        text = text.replace("{{%s}}" % k, str(v))
    if "{{" in text:
        raise ValueError("unfilled placeholder in %s" % text[text.index("{{"):text.index("{{") + 30])
    return text


def render(name, symbol=None, mem=None):
    mem = mem or {}
    p = params(name, mem)
    src = ("Input defaults: best remembered setting for %s in lab/memory.json." % symbol.upper()
           if symbol and name in mem else "Input defaults: the lab's general defaults.")
    vals = dict(p, title=TITLES[name], short="Lab " + TITLES[name], source=src, disclaimer=DISCLAIMER,
                ticker=symbol.upper() if symbol else "the chart")
    text = HEAD + (COMMON if name in INTRADAY else "") + BODY[name] + FOOT
    return fill(text, vals)


def write_all(out=OUT, symbol=None, memory=MEMORY):
    mem = memory_params(symbol, memory)
    os.makedirs(out, exist_ok=True)
    paths = []
    for name in TITLES:
        p = os.path.join(out, name + ".pine")
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(render(name, symbol, mem))
        paths.append(p)
    return paths


def main(argv=None):
    ap = argparse.ArgumentParser(description="export the lab's setups as TradingView Pine v5 (educational)")
    ap.add_argument("--symbol", help="take input defaults from memory.json for this stock")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--memory", default=MEMORY)
    a = ap.parse_args(argv)
    for p in write_all(a.out, a.symbol, a.memory):
        print("wrote %s" % os.path.relpath(p))
    print(DISCLAIMER + ". શૈક્ષણિક હેતુ માટે, રોકાણ સલાહ નથી.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
